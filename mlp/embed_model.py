"""Embed mlp/mlp_outputs/mlp_model.npz and mlp_preprocessing.json into pred.py.

MarkUs accepts only pred.py, so the trained parameters live inside it as
base64 text. Run this from the repository root after retraining:

    python3 mlp/embed_model.py
"""

import base64
import textwrap
from pathlib import Path

MLP_DIR = Path(__file__).resolve().parent
PRED = MLP_DIR.parent / "pred.py"
MARKER = "# --- Embedded model data (generated by mlp/embed_model.py; do not edit) ---"
SOURCES = {
    "_EMBEDDED_MODEL_B64": MLP_DIR / "mlp_outputs" / "mlp_model.npz",
    "_EMBEDDED_PREPROCESSING_B64": MLP_DIR / "mlp_outputs" / "mlp_preprocessing.json",
}


def block(name, path):
    data = base64.b64encode(path.read_bytes()).decode("ascii")
    lines = "\n".join(f'    "{line}"' for line in textwrap.wrap(data, 96))
    return f"{name} = (\n{lines}\n)\n"


def main():
    code = PRED.read_text(encoding="utf-8").split(MARKER)[0].rstrip("\n")
    embedded = "\n".join(block(name, path) for name, path in SOURCES.items())
    PRED.write_text(f"{code}\n\n\n{MARKER}\n{embedded}", encoding="utf-8")
    print(f"Embedded {', '.join(p.name for p in SOURCES.values())} into {PRED.name} "
          f"({PRED.stat().st_size / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
